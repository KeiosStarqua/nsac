// The 3D holo figure for the health card, split into its own chunk: `HologramBody` imports this
// module with `lazy()`, so three.js and the WebGL renderer never reach the HUD entry chunk.
import { useEffect, useMemo, useRef } from "react";
import { Canvas, useFrame, useThree } from "@react-three/fiber";
import { useGLTF } from "@react-three/drei";
import * as THREE from "three";
import { GLTFLoader } from "three/examples/jsm/loaders/GLTFLoader.js";
import { MeshoptDecoder } from "three/examples/jsm/libs/meshopt_decoder.module.js";
import { getStructure, type AnatomySystem } from "open-anatomy-3d";
import { structureKeyForMesh } from "~/features/body-map/model/layers";
import { materialSpec, type MaterialSpec } from "~/features/body-map/model/materials";
import { boxCenter, boxSize } from "~/features/body-map/model/framing";

// The hologram asset is meshopt-compressed (EXT_meshopt_compression), which three's GLTFLoader
// cannot decode unless a decoder is registered. `BodyScene` sets this on the same loader class;
// this module sets it again so the card also works when it is the first scene on the page.
try {
  (GLTFLoader as unknown as { setMeshoptDecoder: (decoder: unknown) => void }).setMeshoptDecoder(MeshoptDecoder);
} catch {
  // ignore — the decoder may already be registered
}

/** Skin + skeleton only, 124,566 tris, ~878 KB. Generated by `scripts/holo-model.ts`. */
const MODEL_URL = "/models/anatomy-male-holo.glb";
/** Vertical field of view; the camera distance is fitted to the model box per canvas size. */
const CAMERA_FOV = 34;
/** Room around the fitted body: 1.08 keeps a hairline of air at the feet and the crown. */
const FRAME_PADDING = 1.08;
/** Slow hologram spin, radians per second. Off under `prefers-reduced-motion`. */
const SPIN_RATE = 0.15;
const MAX_FRAME_DELTA = 0.05;

export interface HoloSceneProps {
  readonly reducedMotion: boolean;
  /** Fired after the first frame with the model in it, so the SVG fallback can step aside. */
  readonly onReady?: () => void;
}

/** Material for one system, from the body map's one spec table. */
function holoSpec(system: AnatomySystem): MaterialSpec {
  const spec = materialSpec(system);
  if (system !== "skeleton") return spec;
  // Bones on a ~120 px card: the body-map spec with its emissive boosted by the documented cap
  // (×1.3 → 0.455), nothing else. The skin shell keeps the body-map spec unchanged.
  return { ...spec, emissiveIntensity: Math.min(1.4, spec.emissiveIntensity * 1.3) };
}

/** The same spec → three-material bridge the body map uses (that module keeps it private). */
function toMaterial(spec: MaterialSpec): THREE.MeshStandardMaterial {
  return new THREE.MeshStandardMaterial({
    color: new THREE.Color(spec.color),
    emissive: new THREE.Color(spec.emissive),
    emissiveIntensity: spec.emissiveIntensity,
    opacity: spec.opacity,
    transparent: spec.transparent,
    depthWrite: spec.depthWrite,
    side: spec.side === "double" ? THREE.DoubleSide : THREE.FrontSide,
    roughness: 0.55,
    metalness: 0.1,
  });
}

function HoloModel({ reducedMotion, onReady }: HoloSceneProps) {
  const { scene } = useGLTF(MODEL_URL, false, true);
  const camera = useThree((state) => state.camera);
  const width = useThree((state) => state.size.width);
  const height = useThree((state) => state.size.height);
  const spinRef = useRef<THREE.Group>(null);

  // One clone with the two system materials applied; the cached glTF scene stays untouched.
  const prepared = useMemo(() => {
    const model = scene.clone(true);
    const materials: THREE.MeshStandardMaterial[] = [];
    model.traverse((node) => {
      if (!(node instanceof THREE.Mesh)) return;
      const key = structureKeyForMesh(node.name);
      const system = key ? (getStructure(key)?.system ?? null) : null;
      if (!system) {
        node.visible = false;
        return;
      }
      const material = toMaterial(holoSpec(system));
      node.material = material;
      materials.push(material);
    });
    return { model, materials };
  }, [scene]);

  useEffect(() => {
    return () => {
      for (const material of prepared.materials) material.dispose();
    };
  }, [prepared]);

  // Fit the whole body into the card box: height against the vertical angle, width against the
  // horizontal one, whichever needs the camera further back.
  useEffect(() => {
    const box = new THREE.Box3().setFromObject(prepared.model);
    const min: [number, number, number] = [box.min.x, box.min.y, box.min.z];
    const max: [number, number, number] = [box.max.x, box.max.y, box.max.z];
    const center = boxCenter({ min, max });
    const extent = boxSize({ min, max });
    const halfVertical = Math.tan((CAMERA_FOV * Math.PI) / 360);
    const aspect = width / Math.max(1, height);
    const distance =
      Math.max(extent[1] / (2 * halfVertical), extent[0] / (2 * halfVertical * aspect)) * FRAME_PADDING;
    camera.position.set(center[0], center[1], center[2] + distance);
    camera.lookAt(center[0], center[1], center[2]);
  }, [prepared, camera, width, height]);

  useEffect(() => {
    onReady?.();
  }, [onReady]);

  useFrame((_, delta) => {
    if (reducedMotion) return;
    const group = spinRef.current;
    if (group) group.rotation.y += SPIN_RATE * Math.min(delta, MAX_FRAME_DELTA);
  });

  return (
    <group ref={spinRef}>
      <primitive object={prepared.model} />
    </group>
  );
}

/**
 * Transparent canvas over the card, framed for the small box. No orbit controls, no picking, no
 * hotspots, no rail: the pointer belongs to the `#hologramButton` link around it.
 */
export default function HoloScene({ reducedMotion, onReady }: HoloSceneProps) {
  return (
    <div className="pointer-events-none absolute inset-0" aria-hidden="true">
      <Canvas
        className="block size-full"
        dpr={[1, 1.75]}
        camera={{ position: [0, 0.95, 3.1], fov: CAMERA_FOV, near: 0.05, far: 20 }}
        frameloop={reducedMotion ? "demand" : "always"}
        gl={{ antialias: true, alpha: true }}
        style={{ background: "transparent", pointerEvents: "none" }}
      >
        <ambientLight intensity={0.55} />
        <hemisphereLight args={["#bfe9ff", "#08101c", 1.1]} />
        <directionalLight position={[2.4, 4.2, 2.8]} intensity={1.35} color="#f4fbff" />
        <pointLight position={[-1.8, 2.2, -1.8]} intensity={14} color="#5eead4" distance={7} decay={2} />
        <HoloModel reducedMotion={reducedMotion} onReady={onReady} />
      </Canvas>
    </div>
  );
}
